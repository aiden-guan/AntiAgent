def resolve_real_agy_executable() -> Optional[str]:
    """Finds the real Google Antigravity CLI executable, avoiding recursion."""
    # 1. Environment variable override
    env_bin = os.getenv("AGY_PATH") or os.getenv("ANTIGRAVITY_PATH")
    if env_bin and os.path.isfile(env_bin) and os.access(env_bin, os.X_OK):
        return env_bin

    # 2. Candidate real paths
    home = Path.home()
    candidates = [
        home / ".local" / "bin" / "agy",
        home / ".antigravity" / "bin" / "agy",
        home / ".gemini" / "antigravity" / "bin" / "agy",
        home / ".gemini" / "bin" / "agy",
        home / "bin" / "agy",
        Path("/usr/local/bin/agy"),
        Path("/opt/homebrew/bin/agy"),
        home / ".local" / "bin" / "antigravity",
        home / "bin" / "antigravity",
        Path("/usr/local/bin/antigravity"),
        Path("/opt/homebrew/bin/antigravity"),
    ]
    for c in candidates:
        if c.is_file() and os.access(c, os.X_OK):
            try:
                text = c.read_text(encoding="utf-8", errors="ignore")[:500]
                if "antiagent agy" in text or "antiagent.cli" in text:
                    continue
            except Exception:
                pass
            return str(c)

    # 3. Check PATH for agy or antigravity
    for name in ("agy", "antigravity"):
        which_bin = shutil.which(name)
        if which_bin:
            try:
                p = Path(which_bin).resolve()
                if p.is_file():
                    text = p.read_text(encoding="utf-8", errors="ignore")[:500]
                    if "antiagent agy" not in text and "antiagent.cli" not in text:
                        return str(p)
            except Exception:
                return which_bin

    # 4. Probe capabilities fallback
    try:
        from antiagent.engine.conversations import detect_agy_capabilities

        caps = detect_agy_capabilities()
        if caps.available and caps.path:
            return caps.path
    except Exception:
        pass

    return None


def launch_agy_cli(agy_args: List[str], workspace_path: str = ".") -> int:
    """Launches AGY with the AntiAgent PTY bridge for prompt queue & steering."""
    from antiagent.engine.interaction_state import InteractionStateStore
    from antiagent.engine.prompt_queue import recover_stale_sessions
    from antiagent.engine.pty_bridge import PTYBridge

    # Recover any stale items from previous crashed sessions into 'held' state
    recover_stale_sessions()

    agy_bin = resolve_real_agy_executable()
    if not agy_bin:
        print("❌ Google Antigravity CLI ('agy') executable not found.")
        print("💡 Please install 'agy' or specify AGY_PATH=/path/to/agy.")
        return 1

    # Ensure hooks are installed so flow state tracking works
    ws_hook = Path(workspace_path).resolve() / ".agents" / "hooks.json"
    global_hook = Path(os.path.expanduser("~/.gemini/config/hooks.json"))
    if not ws_hook.is_file() and not global_hook.is_file():
        try:
            install_hook(is_global=True, quiet=True)
        except Exception:
            pass

    cfg = load_config(workspace_path)
    store = InteractionStateStore.default()
    bridge = PTYBridge(config=cfg, store=store)

    cmd = [agy_bin] + agy_args
    env = os.environ.copy()
    env["_ANTIAGENT_AGY_WRAPPED"] = "1"

    try:
        return bridge.run(cmd, env=env)
    except KeyboardInterrupt:
        return 130
    except Exception as e:
        print(f"\n❌ Error launching AGY wrapper: {e}")
        return 1


def handle_queue_command(args: argparse.Namespace) -> int:
    """Handles antiagent queue status and clear commands."""
    from antiagent.engine.interaction_state import InteractionStateStore
    from antiagent.engine.prompt_queue import PromptQueue

    store = InteractionStateStore.default()
    cid = getattr(args, "conversation_id", None) or store.get_active_conversation_id() or "default"
    queue = PromptQueue(cid)
    state = store.get_state(cid)

    sub = getattr(args, "queue_command", "status") or "status"

    if sub == "status":
        print(f"📋 Prompt Queue Status (Conversation: {cid})")
        print("=" * 50)
        print(f"  Agent State:       {state.state.value}")
        print(f"  Active Surface:    {state.active_surface.value}")
        print(f"  Fully Idle:        {'Yes' if state.fully_idle else 'No'}")
        print(f"  Pending Approval:  {'Yes' if state.pending_approval else 'No'}")
        print(f"  Pending Preview:   {'Yes' if state.pending_preview else 'No'}")
        print(f"  Pending Question:  {'Yes' if state.pending_question else 'No'}")

        items = queue.list_items()
        active = [it for it in items if it.status in ("queued", "dispatching")]
        held = [it for it in items if it.status == "held"]

        print(f"\n  Active Queued Prompts ({len(active)}):")
        if not active:
            print("    (no active prompts queued)")
        else:
            for idx, it in enumerate(active, 1):
                snippet = it.text.replace("\n", " ")
                if len(snippet) > 60:
                    snippet = snippet[:57] + "..."
                print(f"    {idx}. [{it.status.upper()}] (via {it.source}) {snippet}")

        if held:
            print(f"\n  Held Prompts ({len(held)}) [Session Recovery]:")
            for idx, it in enumerate(held, 1):
                snippet = it.text.replace("\n", " ")
                if len(snippet) > 60:
                    snippet = snippet[:57] + "..."
                print(f"    {idx}. [HELD] {snippet}")
        return 0

    elif sub == "clear":
        removed = queue.clear()
        print(f"🧹 Cleared {removed} prompt(s) from queue for conversation {cid}.")
        return 0

    elif sub == "resume":
        resumed = queue.resume_held_items()
        print(f"▶️ Resumed {resumed} held prompt(s) back to active queue for conversation {cid}.")
        return 0

    else:
        print("Available queue subcommands: status, clear, resume")
        return 1


