def get_hook_command() -> str:
    """Returns the shell command to execute the hook."""
    pkg_dir = Path(__file__).resolve().parent
    for parent in pkg_dir.parents:
        if parent.name.endswith(".app"):
            resources_dir = parent / "Contents" / "Resources"
            return f'/usr/bin/env PYTHONPATH="{resources_dir}" python3 -m antiagent.hook'

    py_exec = sys.executable or "python3"
    package_root = pkg_dir.parent
    if not _is_importable_without_pythonpath(py_exec, package_root):
        # Running from an extracted bundle (e.g. AntiAgent-Windows.zip launched via
        # PYTHONPATH). Antigravity spawns the hook without that PYTHONPATH, so
        # `-m antiagent.hook` would fail with ModuleNotFoundError. Route through a
        # launcher script that pins the package location instead.
        launcher = _write_hook_launcher(package_root)
        return f"{_quote_path(py_exec)} {_quote_path(str(launcher))}"
    return f"{_quote_path(py_exec)} -m antiagent.hook"


def _quote_path(path: str) -> str:
    """Quote a path in case it contains spaces (e.g. C:\\Program Files\\Python312\\python.exe)."""
    if " " in path and not (path.startswith('"') and path.endswith('"')):
        return f'"{path}"'
    return path


def _is_importable_without_pythonpath(py_exec: str, package_root: Path) -> bool:
    """Check whether `py_exec` can import this antiagent package without PYTHONPATH help."""
    import subprocess
    import tempfile

    env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}
    probe = "import antiagent, os, sys; sys.stdout.write(os.path.dirname(os.path.dirname(os.path.abspath(antiagent.__file__))))"
    try:
        result = subprocess.run(
            [py_exec, "-c", probe],
            env=env,
            cwd=tempfile.gettempdir(),
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        # Can't probe the interpreter; fall back to the standard module invocation.
        return True
    if result.returncode != 0:
        return False
    try:
        return Path(result.stdout.strip()).resolve() == package_root.resolve()
    except OSError:
        return True


def _write_hook_launcher(package_root: Path) -> Path:
    """Write ~/.antiagent/hook_launcher.py that runs the hook from `package_root`."""
    launcher = get_global_config_dir() / "hook_launcher.py"
    launcher.write_text(
        '"""Auto-generated by AntiAgent: runs the PreToolUse hook from a non-pip install."""\n'
        "import sys\n\n"
        f"sys.path.insert(0, {str(package_root)!r})\n\n"
        "from antiagent.hook import main\n\n"
        "main()\n",
        encoding="utf-8",
    )
    return launcher


def _write_flow_hook_launcher(package_root: Path) -> Path:
    """Write ~/.antiagent/flow_launcher.py that runs the flow hook from `package_root`."""
    launcher = get_global_config_dir() / "flow_launcher.py"
    launcher.write_text(
        '"""Auto-generated by AntiAgent: runs the Flow State hook from a non-pip install."""\n'
        "import sys\n\n"
        f"sys.path.insert(0, {str(package_root)!r})\n\n"
        "from antiagent.flow_hook import main\n\n"
        "main()\n",
        encoding="utf-8",
    )
    return launcher


def get_flow_hook_command(event_arg: str) -> str:
    """Returns the shell command to execute the flow state hook."""
    pkg_dir = Path(__file__).resolve().parent
    for parent in pkg_dir.parents:
        if parent.name.endswith(".app"):
            resources_dir = parent / "Contents" / "Resources"
            return f'/usr/bin/env PYTHONPATH="{resources_dir}" python3 -m antiagent.flow_hook {event_arg}'

    py_exec = sys.executable or "python3"
    package_root = pkg_dir.parent
    if not _is_importable_without_pythonpath(py_exec, package_root):
        launcher = _write_flow_hook_launcher(package_root)
        return f"{_quote_path(py_exec)} {_quote_path(str(launcher))} {event_arg}"
    return f"{_quote_path(py_exec)} -m antiagent.flow_hook {event_arg}"


def install_hook(is_global: bool = False, workspace_path: str = ".", quiet: bool = False) -> None:
    """Install AntiAgent PreToolUse and Flow State hooks into Antigravity configuration."""
    if is_global:
        config_dir = Path(os.path.expanduser("~/.gemini/config"))
        target_desc = f"Global Antigravity config ({config_dir})"
    else:
        config_dir = Path(workspace_path).resolve() / ".agents"
        target_desc = f"Workspace Antigravity config ({config_dir})"

    config_dir.mkdir(parents=True, exist_ok=True)
    hooks_file = config_dir / "hooks.json"

    hooks_data: Dict[str, Any] = {}
    if hooks_file.is_file():
        try:
            with open(hooks_file, "r", encoding="utf-8") as f:
                hooks_data = json.load(f)
        except Exception:
            hooks_data = {}

    # Register antiagent-guard hook (PreToolUse)
    hooks_data["antiagent-guard"] = {
        "enabled": True,
        "PreToolUse": [
            {
                "matcher": "*",
                "hooks": [
                    {
                        "type": "command",
                        "command": get_hook_command(),
                        "timeout": 10,
                    }
                ],
            }
        ],
    }

    # Register antiagent-flow-state hook (PreInvocation, PostInvocation, PostToolUse, Stop)
    hooks_data["antiagent-flow-state"] = {
        "enabled": True,
        "PreInvocation": [
            {
                "type": "command",
                "command": get_flow_hook_command("pre-invocation"),
                "timeout": 10,
            }
        ],
        "PostInvocation": [
            {
                "type": "command",
                "command": get_flow_hook_command("post-invocation"),
                "timeout": 10,
            }
        ],
        "PostToolUse": [
            {
                "matcher": "*",
                "hooks": [
                    {
                        "type": "command",
                        "command": get_flow_hook_command("post-tool-use"),
                        "timeout": 10,
                    }
                ],
            }
        ],
        "Stop": [
            {
                "type": "command",
                "command": get_flow_hook_command("stop"),
                "timeout": 10,
            }
        ],
    }

    import tempfile
    prefix = f".tmp_hooks_{hooks_file.stem}_"
    fd, temp_file = tempfile.mkstemp(dir=config_dir, prefix=prefix, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(hooks_data, f, indent=2)
            f.flush()
        os.replace(temp_file, hooks_file)
    finally:
        if os.path.exists(temp_file):
            try:
                os.remove(temp_file)
            except OSError:
                pass

    if not quiet:
        print(f"✅ Successfully installed AntiAgent hooks to {target_desc} -> {hooks_file}")
        print("   • antiagent-guard: Reviews tool calls before execution.")
        print("   • antiagent-flow-state: Tracks agent lifecycle for prompt queue & steering.")


def uninstall_hook(is_global: bool = False, workspace_path: str = ".") -> None:
    """Uninstall AntiAgent hooks from Antigravity configuration."""
    if is_global:
        config_dir = Path(os.path.expanduser("~/.gemini/config"))
    else:
        config_dir = Path(workspace_path).resolve() / ".agents"

    hooks_file = config_dir / "hooks.json"
    if not hooks_file.is_file():
        print(f"ℹ️ No hooks.json found at {hooks_file}")
        return

    try:
        with open(hooks_file, "r", encoding="utf-8") as f:
            hooks_data = json.load(f)
    except Exception:
        hooks_data = {}

    removed = False
    if "antiagent-guard" in hooks_data:
        del hooks_data["antiagent-guard"]
        removed = True
    if "antiagent-flow-state" in hooks_data:
        del hooks_data["antiagent-flow-state"]
        removed = True

    if removed:
        import tempfile
        prefix = f".tmp_hooks_{hooks_file.stem}_"
        fd, temp_file = tempfile.mkstemp(dir=config_dir, prefix=prefix, text=True)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(hooks_data, f, indent=2)
                f.flush()
            os.replace(temp_file, hooks_file)
        finally:
            if os.path.exists(temp_file):
                try:
                    os.remove(temp_file)
                except OSError:
                    pass
        print(f"✅ Successfully removed AntiAgent hooks from {hooks_file}")
    else:
        print(f"ℹ️ AntiAgent hooks were not installed in {hooks_file}")


